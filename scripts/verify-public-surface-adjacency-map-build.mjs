// Phase 3A P6 generated-output verifier — expanded public surface adjacency map.
//
// Runs AFTER `astro build` (so `dist/` exists). Verifies that the generated
// expanded-adjacency surface is byte-identical to the repository source,
// validates against the production contracts, confirms the required visible
// public content and boundary wording, and asserts that no external runtime data
// URL, prohibited field, or relation promotion leaked into the build.
//
// This verifier is INDEPENDENT of scripts/verify-public-surface-map-build.mjs.
// It never reads, weakens, or replaces that verifier, and the frozen 30-record
// product is checked here only to prove it stayed byte-identical.
//
// It makes no network request and never writes into source files.
//
// Node 22 strips TypeScript types on import, so the production `.ts` contracts
// are imported directly and exercised against the generated bytes.

