const results = [];
let failed = 0;

async function check(name, fn) {
  try {
    const detail = await fn();
    results.push(`PASS  ${name}${detail ? ` — ${detail}` : ""}`);
  } catch (error) {
    failed += 1;
    results.push(`FAIL  ${name} — ${error.message}`);
  }
}

const readBytes = (path) => new Uint8Array(readFileSync(path));

function bytesEqual(a, b) {
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length; i += 1) if (a[i] !== b[i]) return false;
  return true;
}

function requireExists(path, label) {
  if (!existsSync(path)) throw new Error(`${label} is missing: ${path}`);
  return path;
}

async function identityOf(bytes) {
  return {
    byteLength: bytes.length,
    sha256: await sha256Hex(bytes),
    gitBlob: await gitBlobSha1Hex(bytes),
  };
}

function clientJsFiles() {
  if (!existsSync(DIST_ASTRO)) return [];
  return readdirSync(DIST_ASTRO)
    .filter((f) => f.endsWith(".js"))
    .map((f) => p(`dist/_astro/${f}`));
}

function clientCssFiles() {
  if (!existsSync(DIST_ASTRO)) return [];
  return readdirSync(DIST_ASTRO)
    .filter((f) => f.endsWith(".css"))
    .map((f) => p(`dist/_astro/${f}`));
}

function sitemapFiles() {
  return readdirSync(DIST_SITEMAP_DIR)
    .filter((f) => f.startsWith("sitemap") && f.endsWith(".xml"))
    .map((f) => p(`dist/${f}`));
}

