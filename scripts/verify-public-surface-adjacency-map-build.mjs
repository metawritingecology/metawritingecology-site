await check("PSADJ-09 required visible content is present", () => {
  const html = readFileSync(DIST_PAGE, "utf8");
  const snapshot = assertAdjacencySnapshot(JSON.parse(readFileSync(SRC_FALLBACK, "utf8")));

  const required = [
    APPROVED_TITLE,
    SCOPE_STATEMENT,
    RELATIONSHIP_SENTENCE,
    AUTHORITY_VIEW_LABEL,
    EXPANDED_VIEW_LABEL,
    `href="${AUTHORITY_ROUTE}"`,
    `href="${PARENT_ROUTE}"`,
    SELECTED_SOURCE_COMMIT,
    SELECTED_SHA256,
    "Source-declared adjacency",
    "Provisional navigation adjacency",
    "solid line, filled arrow head",
    "dashed line, open arrow head",
    // P7.1 required visible wording.
    GROUP_ARC_STATEMENT,
    ROLE_ORBIT_CAPTION,
    RECORD_ORDER_DISCLAIMER,
    ...CENTRAL_STATEMENT_LINES,
  ];
  const missing = required.filter((needle) => !html.includes(needle));
  if (missing.length > 0) throw new Error(`missing visible content: ${missing.join(" | ")}`);

  // Every dataset boundary statement and every not-claim is rendered.
  const missingBoundary = snapshot.boundary_statements.filter((statement) => {
    // Astro escapes apostrophes in text nodes; compare on the escaped form too.
    const escaped = statement.replace(/'/g, "&#39;").replace(/&(?!#?\w+;)/g, "&amp;");
    return !html.includes(statement) && !html.includes(escaped);
  });
  if (missingBoundary.length > 0) {
    throw new Error(`missing boundary statement(s): ${missingBoundary.length}`);
  }
  const missingClaims = NOT_CLAIMS.filter((claim) => !html.includes(claim));
  if (missingClaims.length > 0) throw new Error(`missing not-claim(s): ${missingClaims.join(" | ")}`);

  // Node and edge counts are stated.
  for (const [attr, value] of [
    ["data-psadj-record-count", EXPECTED_RECORD_COUNT],
    ["data-psadj-semantic-count", EXPECTED_SEMANTIC_LAYOUT_PARTICIPANTS],
    ["data-psadj-band-count", EXPECTED_FIXED_BAND_RECORDS],
    ["data-psadj-edge-count", EXPECTED_TOTAL_EDGES],
    ["data-psadj-source-named-count", EXPECTED_EDGE_COUNTS.source_named_adjacency],
    ["data-psadj-navigation-count", EXPECTED_EDGE_COUNTS.navigation_adjacency],
  ]) {
    const found = new RegExp(`${attr}[^>]*>${value}<`).test(html);
    if (!found) throw new Error(`${attr} does not state ${value}`);
  }

  // A live status region and the runtime/fallback status are present.
  for (const marker of ['aria-live="polite"', 'role="status"', "data-psadj-runtime-status"]) {
    if (!html.includes(marker)) throw new Error(`missing ${marker}`);
  }
  return `${snapshot.boundary_statements.length} boundary statements, ${NOT_CLAIMS.length} not-claims, counts, legend, links, status`;
});

