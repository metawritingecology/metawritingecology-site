await check("PSADJ-10 fallback lists every one of the 59 records", () => {
  const html = readFileSync(DIST_PAGE, "utf8");
  const snapshot = assertAdjacencySnapshot(JSON.parse(readFileSync(SRC_FALLBACK, "utf8")));

  const rendered = [...html.matchAll(/data-psadj-record="([^"]+)"/g)].map((m) => m[1]);
  if (rendered.length !== EXPECTED_RECORD_COUNT) {
    throw new Error(`fallback renders ${rendered.length} records, expected ${EXPECTED_RECORD_COUNT}`);
  }
  const renderedSet = new Set(rendered);
  const missing = snapshot.nodes.filter((node) => !renderedSet.has(node.id));
  if (missing.length > 0) {
    throw new Error(`fallback is missing ${missing.length} record id(s): ${missing[0].id}`);
  }
  // The record list must not be hidden behind a control.
  if (/data-psadj-record-list[^>]*\bhidden\b/.test(html)) {
    throw new Error("the fallback record list is hidden");
  }
  const listIndex = html.indexOf("data-psadj-record-list");
  if (listIndex === -1) throw new Error("the fallback record list is absent");
  return `${rendered.length} record ids rendered and visible without JavaScript`;
});

