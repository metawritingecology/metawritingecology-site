// ---------------------------------------------------------------------------
// PSADJ-12 — header rules present and exact
// ---------------------------------------------------------------------------

await check("PSADJ-12 generated header rules are exact", () => {
  const text = readFileSync(requireExists(DIST_HEADERS, "generated _headers"), "utf8").replace(
    /\r\n?/g,
    "\n",
  );
  const blocks = [];
  let current = null;
  for (const raw of text.split("\n")) {
    if (raw.trim() === "") continue;
    if (/^\s/.test(raw)) {
      if (current) current.body.push(raw.trim());
      continue;
    }
    current = { path: raw.trim(), body: [] };
    blocks.push(current);
  }

  const expect = (path, body) => {
    const matches = blocks.filter((block) => block.path === path);
    if (matches.length !== 1) {
      throw new Error(`expected exactly one "${path}" rule, found ${matches.length}`);
    }
    const actual = matches[0].body;
    if (actual.length !== body.length || actual.some((line, i) => line !== body[i])) {
      throw new Error(`"${path}" body mismatch: ${actual.join(" | ")}`);
    }
  };

  expect("/public-surface-map/expanded/data/manifest.json", [
    "Content-Type: application/json; charset=utf-8",
    "Cache-Control: no-cache, must-revalidate",
    "X-Content-Type-Options: nosniff",
    "X-Robots-Tag: noindex, nofollow, nosnippet",
  ]);
  expect("/public-surface-map/expanded/data/snapshots/*", [
    "Content-Type: application/json; charset=utf-8",
    "Cache-Control: public, max-age=31536000, immutable",
    "X-Content-Type-Options: nosniff",
    "X-Robots-Tag: noindex, nofollow, nosnippet",
  ]);

  // The frozen product's own rules must be untouched.
  expect("/public-surface-map/data/manifest.json", [
    "Content-Type: application/json; charset=utf-8",
    "Cache-Control: no-cache, must-revalidate",
    "X-Robots-Tag: noindex, nofollow, nosnippet",
  ]);
  expect("/public-surface-map/data/snapshots/*", [
    "Content-Type: application/json; charset=utf-8",
    "Cache-Control: public, max-age=31536000, immutable",
    "X-Robots-Tag: noindex, nofollow, nosnippet",
  ]);
  return "expanded manifest and snapshot rules exact; authority-map rules unchanged";
});

// ---------------------------------------------------------------------------
// PSADJ-13 — JSON MIME expectations
// ---------------------------------------------------------------------------

await check("PSADJ-13 JSON endpoints are JSON and parse", () => {
  for (const [label, path] of [
    ["manifest", DIST_MANIFEST],
    ["snapshot", DIST_SNAPSHOT],
  ]) {
    if (!path.endsWith(".json")) throw new Error(`${label} route is not extension-bearing JSON`);
    const text = readFileSync(path, "utf8");
    try {
      JSON.parse(text);
    } catch (error) {
      throw new Error(`${label} body is not valid JSON: ${error.message}`);
    }
    if (/^\s*</.test(text)) throw new Error(`${label} body looks like HTML`);
  }
  // The endpoint modules declare the JSON content type explicitly.
  for (const source of [
    "src/pages/public-surface-map/expanded/data/manifest.json.ts",
    `src/pages/public-surface-map/expanded/data/snapshots/[snapshotId].json.ts`,
  ]) {
    const code = readFileSync(p(source), "utf8");
    if (!code.includes('"content-type": "application/json; charset=utf-8"')) {
      throw new Error(`${source} does not declare the JSON content type`);
    }
    if (!code.includes("export const prerender = true")) {
      throw new Error(`${source} is not prerendered`);
    }
    if (/JSON\.stringify\(/.test(code)) {
      throw new Error(`${source} must serve raw bytes, never a reserialized body`);
    }
  }
  return "application/json; charset=utf-8, prerendered, raw bytes only";
});

