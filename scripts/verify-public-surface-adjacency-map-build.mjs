// ---------------------------------------------------------------------------
// PSADJ-02 — runtime manifest exact contract and exact bytes
// ---------------------------------------------------------------------------

await check("PSADJ-02 runtime manifest exact contract and bytes", async () => {
  const distBytes = readBytes(DIST_MANIFEST);
  const srcBytes = readBytes(SRC_MANIFEST);
  if (!bytesEqual(distBytes, srcBytes)) {
    throw new Error("generated manifest bytes differ from the repository source");
  }
  const manifest = assertAdjacencyRuntimeManifest(JSON.parse(readFileSync(DIST_MANIFEST, "utf8")));
  if (manifest.map_id !== "public-surface-adjacency-map") {
    throw new Error(`unexpected map_id ${manifest.map_id}`);
  }
  if (manifest.currentness_claim !== "none") {
    throw new Error("manifest must declare currentness_claim none");
  }
  if (manifest.selected_snapshot.path !== snapshotPathForId(SELECTED_SNAPSHOT_ID)) {
    throw new Error("manifest snapshot path is not the approved route path");
  }
  if (!manifest.selected_snapshot.path.startsWith(SNAPSHOT_ROUTE_PREFIX)) {
    throw new Error("manifest snapshot path escapes the route namespace");
  }
  const identity = await identityOf(distBytes);
  return `${identity.byteLength} bytes, sha256 ${identity.sha256.slice(0, 12)}…, blob ${identity.gitBlob.slice(0, 12)}…`;
});

// ---------------------------------------------------------------------------
// PSADJ-03 — snapshot exact bytes, byte length, SHA-256, Git blob
// ---------------------------------------------------------------------------

await check("PSADJ-03 snapshot exact byte identity", async () => {
  const distBytes = readBytes(DIST_SNAPSHOT);
  const identity = await identityOf(distBytes);
  if (identity.byteLength !== SELECTED_BYTE_LENGTH) {
    throw new Error(`byte length ${identity.byteLength}, expected ${SELECTED_BYTE_LENGTH}`);
  }
  if (identity.sha256 !== SELECTED_SHA256) throw new Error("SHA-256 mismatch");
  if (identity.gitBlob !== SELECTED_GIT_BLOB) throw new Error("Git blob mismatch");

  const manifest = assertAdjacencyRuntimeManifest(JSON.parse(readFileSync(DIST_MANIFEST, "utf8")));
  assertManifestMatchesSnapshot(manifest, { id: SELECTED_SNAPSHOT_ID, ...identity });
  return `${identity.byteLength} bytes, sha256 ${identity.sha256}, blob ${identity.gitBlob}`;
});

// ---------------------------------------------------------------------------
// PSADJ-04 — source snapshot and bundled fallback are byte identical
// ---------------------------------------------------------------------------

await check("PSADJ-04 snapshot, fallback and generated bytes are identical", async () => {
  const src = readBytes(SRC_SNAPSHOT);
  const fallback = readBytes(SRC_FALLBACK);
  const dist = readBytes(DIST_SNAPSHOT);
  if (!bytesEqual(src, fallback)) {
    throw new Error("bundled fallback is not byte-identical to the immutable snapshot");
  }
  if (!bytesEqual(src, dist)) {
    throw new Error("generated snapshot is not byte-identical to the repository source");
  }
  const identity = await identityOf(fallback);
  if (identity.sha256 !== SELECTED_SHA256 || identity.gitBlob !== SELECTED_GIT_BLOB) {
    throw new Error("bundled fallback identity does not match the adopted dataset");
  }
  return "immutable snapshot == bundled fallback == generated bytes";
});

// ---------------------------------------------------------------------------
// PSADJ-05 — dataset contract over the generated bytes
// ---------------------------------------------------------------------------

await check("PSADJ-05 generated dataset satisfies the full contract", () => {
  const snapshot = assertAdjacencySnapshot(JSON.parse(readFileSync(DIST_SNAPSHOT, "utf8")));
  if (snapshot.nodes.length !== EXPECTED_RECORD_COUNT) {
    throw new Error(`node count ${snapshot.nodes.length}`);
  }
  if (snapshot.edges.length !== EXPECTED_TOTAL_EDGES) {
    throw new Error(`edge count ${snapshot.edges.length}`);
  }
  if (snapshot.source_commit !== SELECTED_SOURCE_COMMIT) {
    throw new Error("generated snapshot source commit mismatch");
  }
  const roles = {};
  for (const node of snapshot.nodes) {
    roles[node.visualization_role] = (roles[node.visualization_role] ?? 0) + 1;
  }
  for (const [role, expected] of Object.entries(EXPECTED_ROLE_COUNTS)) {
    if (roles[role] !== expected) throw new Error(`role ${role}: ${roles[role]}, expected ${expected}`);
  }
  const participants = snapshot.nodes.filter((n) => n.semantic_layout_participation).length;
  if (participants !== EXPECTED_SEMANTIC_LAYOUT_PARTICIPANTS) {
    throw new Error(`semantic participants ${participants}`);
  }
  if (snapshot.nodes.length - participants !== EXPECTED_FIXED_BAND_RECORDS) {
    throw new Error("fixed-band record count mismatch");
  }
  const classes = {};
  for (const edge of snapshot.edges) {
    classes[edge.edge_class] = (classes[edge.edge_class] ?? 0) + 1;
  }
  for (const [edgeClass, expected] of Object.entries(EXPECTED_EDGE_COUNTS)) {
    if (classes[edgeClass] !== expected) {
      throw new Error(`${edgeClass}: ${classes[edgeClass]}, expected ${expected}`);
    }
  }
  return `59 records (49/2/7/1), 49 semantic + 10 fixed band, 383 edges (189 + 194)`;
});

// ---------------------------------------------------------------------------
// PSADJ-06 — no prohibited field, no relation promotion
// ---------------------------------------------------------------------------

await check("PSADJ-06 no prohibited field or relation promotion", () => {
  const raw = readFileSync(DIST_SNAPSHOT, "utf8");
  assertNoProhibitedSemantics(JSON.parse(raw));

  const snapshot = JSON.parse(raw);
  for (const edge of snapshot.edges) {
    if (RELATION_CLASSES_NOT_RENDERED.includes(edge.edge_class)) {
      throw new Error(`a not-rendered relation class was published: ${edge.edge_class}`);
    }
    if (edge.relation_status !== edge.edge_class) {
      throw new Error("edge relation status was promoted away from its evidence class");
    }
    if (edge.authority_ceiling !== "navigation_only") {
      throw new Error("edge authority ceiling was widened");
    }
  }

  // The generated page's VISIBLE prose must not publish a promoted relation
  // vocabulary. The embedded JSON data island is excluded from this scan: it is
  // the validated dataset itself, whose `relation_classes_not_rendered` array
  // legitimately names the four classes precisely in order to exclude them.
  const html = readFileSync(DIST_PAGE, "utf8");
  const prose = html.replace(
    /<script type="application\/json" data-psadj-data>[\s\S]*?<\/script>/g,
    "",
  );
  if (prose.length === html.length) {
    throw new Error("the JSON data island was not found, so the prose scan is unreliable");
  }
  for (const forbidden of [
    "user_confirmed_relation",
    "confirmed relation graph of",
    "formal dependency between",
    "supersedes the 30",
    "the canonical graph",
  ]) {
    if (prose.includes(forbidden)) throw new Error(`page prose publishes "${forbidden}"`);
  }
  return "no confirmed/rank/centrality/authority-score/currentness field";
});

// ---------------------------------------------------------------------------
// PSADJ-07 — page metadata: noindex, canonical, title, description
// ---------------------------------------------------------------------------

await check("PSADJ-07 page metadata is noindex and self canonical", () => {
  const html = readFileSync(DIST_PAGE, "utf8");

  const robots = [...html.matchAll(/<meta\s+name="robots"\s+content="([^"]*)"/gi)].map((m) => m[1]);
  if (robots.length !== 1) throw new Error(`expected exactly one robots meta, found ${robots.length}`);
  if (!/^noindex,\s*nofollow$/i.test(robots[0])) {
    throw new Error(`robots must be "noindex, nofollow", found "${robots[0]}"`);
  }

  const canonicals = [...html.matchAll(/<link\s+rel="canonical"\s+href="([^"]*)"/gi)].map((m) => m[1]);
  if (canonicals.length !== 1) throw new Error(`expected exactly one canonical, found ${canonicals.length}`);
  if (canonicals[0] !== CANONICAL_URL) {
    throw new Error(`canonical must be ${CANONICAL_URL}, found ${canonicals[0]}`);
  }

  if (!html.includes(`<title>${APPROVED_TITLE}</title>`)) {
    throw new Error("approved page title is missing");
  }
  if (!html.includes(APPROVED_DESCRIPTION)) throw new Error("approved description is missing");

  const jsonLd = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
  if (jsonLd.length !== 1) throw new Error(`expected exactly one JSON-LD block, found ${jsonLd.length}`);
  const graph = JSON.parse(jsonLd[0][1]);
  const types = graph["@graph"].map((node) => node["@type"]);
  for (const type of types) {
    if (!["WebSite", "WebPage"].includes(type)) throw new Error(`JSON-LD type outside ceiling: ${type}`);
  }
  const webpage = graph["@graph"].find((node) => node["@type"] === "WebPage");
  if (webpage.url !== CANONICAL_URL) throw new Error("WebPage url is not the canonical URL");
  if (webpage.description !== APPROVED_DESCRIPTION) {
    throw new Error("WebPage description is not the approved description");
  }
  return `noindex, nofollow; canonical ${CANONICAL_URL}; WebSite+WebPage only`;
});

