// Phase 2A generated-output verifier.
//
// Runs AFTER `astro build` (so `dist/` exists). Verifies that the prerendered
// data surface in `dist/` is byte-identical to the repository source, validates
// against the production contracts, and asserts that no Phase 2B browser runtime
// behavior or external runtime URL leaked into the build. Makes no network
// requests and never writes into source files.
//
// Check 19 additionally enforces the Phase 2A D3 boundary: the deterministic
// Authority-View renderer must be bundled from the locally installed
// `d3-selection` package, with no CDN or remote-ESM source, no excluded D3
// module (force, drag, zoom, hierarchy, geo), no canvas/WebGL context, no code
// evaluation, and no HTML writing of snapshot metadata.
//
// Check 20 enforces the Phase 2B-1 viewport boundary: the repository's own
// bounded viewport implementation and its native controls must be present, no
// npm package may have been added for it, the transient viewport state must not
// be persisted anywhere, and no gesture-only navigation route may exist.
// Checks 1-19 are unchanged in effect; check 19(e) additionally scans the new
// viewport module for HTML-writing APIs.
//
// Node 22 strips TypeScript types on import, so the production `.ts` contracts
// are imported directly and exercised against the generated bytes.

